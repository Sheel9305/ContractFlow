  cy.visit("http://localhost:3000");
  cy.get('[data-cy="login-link"]').should("be.visible").click();
  cy.get('[data-cy="username"]').type("admin");
  cy.get('[data-cy="password"]').type("pass@123");
  cy.get('[data-cy="login-btn"]').click();

